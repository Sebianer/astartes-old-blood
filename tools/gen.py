"""Preflight the sheets and generate the data the hook (C++) and launcher (C#) are built from.

Usage: python tools/gen.py [<Space Marine 2 root>]
With the SM2 root, sfx events are resolved to Wwise media ids (needs the player's paks); without it the
previous ids in sheets/sfx_resolved.json are reused.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))


def sheet(name):
    with open(os.path.join(ROOT, "sheets", name + ".json"), encoding="utf-8") as f:
        d = json.load(f)
    for r in d.get("rows", []):
        missing = [c for c in d.get("columns", []) if c not in r]
        if missing:
            sys.exit(f"{name}: row {r.get('id')} missing {missing}")
    return d["rows"]


def preflight(classes, abilities, voice, sfx, hooks, hud):
    errs = []
    ab_ids = {a["id"] for a in abilities}
    sfx_ids = {s["id"] for s in sfx}
    effects = {"invuln", "surge", "turret", "restore", "dash", "slowmo", "damageBuff"}
    for c in classes:
        if c["ability"] not in ab_ids:
            errs.append(f"class {c['id']}: unknown ability {c['ability']}")
        for k in ("runSpeed", "sprintSpeed", "jumpHeight"):
            if not 20 <= c[k] <= 2000:
                errs.append(f"class {c['id']}: {k} {c[k]} out of range")
        for k in ("damageTaken", "damageDealt"):
            if not 0 < c[k] <= 5:
                errs.append(f"class {c['id']}: {k} {c[k]} out of range")
    for a in abilities:
        if a["effect"] not in effects:
            errs.append(f"ability {a['id']}: unknown effect {a['effect']}")
        if a["sfx"] not in sfx_ids:
            errs.append(f"ability {a['id']}: unknown sfx {a['sfx']}")
        if a["cooldown"] < a["duration"]:
            errs.append(f"ability {a['id']}: cooldown shorter than duration")
    needed_voice = {"deploy", "kill", "lowHealth", "hover", "abilityReady"}
    if needed_voice - {v["id"] for v in voice}:
        errs.append(f"voice: missing {needed_voice - {v['id'] for v in voice}}")
    hk = {h["id"] for h in hooks}
    for k in ("imageSize", "gameLocal", "entities", "vtAI", "vfHealthComp", "vfHealth", "vfMaxHealth", "plHealth",
              "plArmour", "plArmourMax", "evKill", "postEvent"):
        if k not in hk:
            errs.append(f"hooks: missing {k}")
    if errs:
        sys.exit("preflight failed:\n  " + "\n  ".join(errs))


def resolve_sfx(sfx, sm2_root):
    path = os.path.join(ROOT, "sheets", "sfx_resolved.json")
    if not sm2_root:
        with open(path) as f:
            return json.load(f)
    import wwise
    banks, out = {}, {}
    for s in sfx:
        if s["bank"] not in banks:
            banks[s["bank"]] = wwise.load(sm2_root, s["bank"])
        bank, streamed = banks[s["bank"]]
        ids = wwise.resolve(bank, streamed, s["event"])
        if not ids:
            sys.exit(f"sfx {s['id']}: event {s['event']} not found in bank {s['bank']}")
        size = lambda m: bank.media[m][1] if m in bank.media else 0
        out[s["id"]] = sorted(ids, key=size, reverse=True)
    with open(path, "w") as f:
        json.dump(out, f, indent=1)
    return out


def cstr(s):
    return json.dumps(s)


def fl(x):
    return repr(float(x)) + "f"


def write(path, text):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", path)


def gen_cpp(classes, abilities, voice, hooks, hud):
    ab_index = {a["id"]: i for i, a in enumerate(abilities)}
    L = ["// Generated by tools/gen.py from sheets/*.json - do not edit.", "#pragma once", ""]
    for h in hooks:
        L.append(f"#define HK_{h['id']} {h['value']}  // {h['note']}")
    L += ["", "enum Effect { FX_invuln, FX_surge, FX_turret, FX_restore, FX_dash, FX_slowmo, FX_damageBuff };", ""]
    L.append("struct AbilityDef { const char* id; const char* name; Effect effect; float duration, cooldown, speedMul, jumpMul, power, interval, range; const char* sfx; };")
    L.append("static const AbilityDef kAbilities[] = {")
    for a in abilities:
        L.append(f"  {{{cstr(a['id'])}, {cstr(a['name'])}, FX_{a['effect']}, {fl(a['duration'])}, {fl(a['cooldown'])}, {fl(a['speedMul'])}, {fl(a['jumpMul'])}, {fl(a['power'])}, {fl(a['interval'])}, {fl(a['range'])}, {cstr(a['sfx'])}}},")
    L.append("};")
    L.append("struct ClassDef { const char* id; const char* name; float runSpeed, sprintSpeed, jumpHeight, damageTaken, damageDealt; int ability; };")
    L.append("static const ClassDef kClasses[] = {")
    for c in classes:
        L.append(f"  {{{cstr(c['id'])}, {cstr(c['name'])}, {fl(c['runSpeed'])}, {fl(c['sprintSpeed'])}, {fl(c['jumpHeight'])}, {fl(c['damageTaken'])}, {fl(c['damageDealt'])}, {ab_index[c['ability']]}}},")
    L.append("};")
    L.append("struct VoiceDef { const char* id; float chance, cooldown; };")
    L.append("static const VoiceDef kVoice[] = {")
    for v in voice:
        L.append(f"  {{{cstr(v['id'])}, {fl(v['chance'])}, {fl(v['cooldown'])}}},")
    L.append("};")
    for h in hud:
        v = h["value"]
        if isinstance(v, list):
            L.append(f"static const unsigned char HUD_{h['id']}[4] = {{{', '.join(map(str, v))}}};")
        elif isinstance(v, str):
            L.append(f"static const char HUD_{h['id']} = '{v}';")
        else:
            L.append(f"static const float HUD_{h['id']} = {fl(v)};")
    write("hook/gen_data.h", "\n".join(L) + "\n")


def gen_cs(classes, abilities, voice, sfx, resolved, hud):
    ab = {a["id"]: a for a in abilities}
    L = ["// Generated by tools/gen.py from sheets/*.json - do not edit.", "static class GenData {"]
    key = next(h["value"] for h in hud if h["id"] == "abilityKey")
    L.append(f"    public const string AbilityKey = {cstr(key)};")
    L.append("    public class ClassRow { public string Id, Name, Sm2Id, VoiceId, AbilityName, AbilityText, AbilityVoice; public float Run, Sprint, Jump, Taken, Dealt; }")
    L.append("    public static readonly ClassRow[] Classes = {")
    for c in classes:
        a = ab[c["ability"]]
        L.append(f"        new ClassRow {{ Id = {cstr(c['id'])}, Name = {cstr(c['name'])}, Sm2Id = {cstr(c['sm2Id'])}, VoiceId = {cstr(c['voiceId'])}, "
                 f"AbilityName = {cstr(a['name'])}, AbilityText = {cstr(a['text'])}, AbilityVoice = {cstr(a['voiceEvent'])}, Run = {fl(c['runSpeed'])}, Sprint = {fl(c['sprintSpeed'])}, "
                 f"Jump = {fl(c['jumpHeight'])}, Taken = {fl(c['damageTaken'])}, Dealt = {fl(c['damageDealt'])} }},")
    L.append("    };")
    L.append("    // voice role -> SM2 event; \"ability\" is per class (AbilityVoice)")
    L.append("    public static readonly string[][] Voice = {")
    for v in voice:
        L.append(f"        new[] {{ {cstr(v['id'])}, {cstr(v['event'])} }},")
    L.append("    };")
    L.append("    public class SfxRow { public string Id, Bank; public uint[] Media; }")
    L.append("    public static readonly SfxRow[] Sfx = {")
    for s in sfx:
        L.append(f"        new SfxRow {{ Id = {cstr(s['id'])}, Bank = {cstr(s['bank'])}, Media = new uint[] {{ {', '.join(str(m) + 'u' for m in resolved[s['id']])} }} }},")
    L.append("    };")
    L.append("}")
    write("launcher/GenData.cs", "\n".join(L) + "\n")


def main():
    classes, abilities, voice = sheet("classes"), sheet("abilities"), sheet("voice")
    sfx, hooks, hud = sheet("sfx"), sheet("hooks"), sheet("hud")
    preflight(classes, abilities, voice, sfx, hooks, hud)
    resolved = resolve_sfx(sfx, sys.argv[1] if len(sys.argv) > 1 else None)
    gen_cpp(classes, abilities, voice, hooks, hud)
    gen_cs(classes, abilities, voice, sfx, resolved, hud)
    print("preflight ok:", len(classes), "classes,", len(abilities), "abilities,", len(sfx), "sfx")


if __name__ == "__main__":
    main()
